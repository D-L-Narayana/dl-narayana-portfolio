const{chromium}=require('playwright');
(async()=>{
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1280,height:800}});
const errs=[];
p.on('pageerror',e=>errs.push('PAGE:'+e.message));
p.on('console',m=>{if(m.type()==='error')errs.push('CON:'+m.text());});
await p.goto('http://localhost:8096/',{waitUntil:'domcontentloaded'});
await p.waitForTimeout(10800);
await p.screenshot({path:'shots/x1-name.png'});
const navs=await p.locator('.navItem').count();
await p.locator('.navItem[data-m="about"]').click();
await p.waitForTimeout(1400);
await p.screenshot({path:'shots/x2-about.png'});
await p.locator('.navItem[data-m="resume"]').click();
await p.waitForTimeout(1400);
await p.screenshot({path:'shots/x3-resume.png'});
await p.locator('.navItem[data-m="projects"]').click();
await p.waitForTimeout(1800);
await p.screenshot({path:'shots/x4-projects.png'});
const cards=await p.locator('.card').count();
await p.locator('.navItem[data-m="home"]').click();
await p.waitForTimeout(1400);
await p.screenshot({path:'shots/x5-home.png'});
await b.close();
console.log('E2E_RESULTS '+JSON.stringify({navs:navs,cards:cards,errors:errs}));
if(navs!==4||cards!==3)process.exit(1);
})().catch(e=>{console.error('E2E_FAIL',e.message);process.exit(1);});

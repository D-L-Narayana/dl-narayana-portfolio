const{chromium}=require('playwright');
(async()=>{
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1280,height:800}});
const errs=[];
p.on('pageerror',e=>errs.push('PAGE:'+e.message));
p.on('console',m=>{if(m.type()==='error')errs.push('CON:'+m.text());});
await p.goto('http://localhost:8101/',{waitUntil:'domcontentloaded'});
await p.waitForTimeout(1000);
await p.screenshot({path:'shots/m0-loader.png'});
await p.waitForTimeout(3600);
await p.screenshot({path:'shots/m1-home.png'});
const nameVis=await p.locator('#nwrap').isVisible();
const nameTxt=(await p.locator('#name').textContent()).replace(/\u00a0/g,' ');
await p.mouse.move(640,400);
await p.mouse.wheel(0,150);
await p.waitForTimeout(2300);
await p.screenshot({path:'shots/m2-portrait.png'});
await p.locator('.navItem[data-m="projects"]').click();
await p.waitForTimeout(1800);
const cards=await p.locator('.card').count();
await p.screenshot({path:'shots/m3-projects.png'});
await p.locator('.navItem[data-m="contact"]').click();
await p.waitForTimeout(1600);
await p.screenshot({path:'shots/m4-contact.png'});
await p.locator('.navItem[data-m="home"]').click();
await p.waitForTimeout(1600);
const back=await p.locator('#nwrap').isVisible();
await p.screenshot({path:'shots/m5-home.png'});
await b.close();
console.log('E2E_RESULTS '+JSON.stringify({nameVis:nameVis,nameTxt:nameTxt,cards:cards,back:back,errors:errs}));
if(!nameVis||cards!==3||!back)process.exit(1);
})().catch(e=>{console.error('E2E_FAIL',e.message);process.exit(1);});

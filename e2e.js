const{chromium}=require('playwright');
(async()=>{
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1280,height:800}});
const errs=[];
p.on('pageerror',e=>errs.push('PAGE:'+e.message));
p.on('console',m=>{if(m.type()==='error')errs.push('CON:'+m.text());});
await p.goto('http://localhost:8097/',{waitUntil:'domcontentloaded'});
await p.waitForTimeout(10800);
await p.screenshot({path:'shots/y1-home.png'});
const start=await p.locator('#btnStart').count();
const pill=await p.locator('#introPill').count();
await p.locator('#introPill').hover();
await p.waitForTimeout(700);
await p.screenshot({path:'shots/y1b-pill.png'});
await p.locator('.navItem[data-m="about"]').click();
await p.waitForTimeout(1700);
await p.screenshot({path:'shots/y2-about.png'});
const asciiLen=await p.evaluate(()=>document.getElementById('asciiPre').textContent.length);
const iconOk=await p.evaluate(()=>{const i=document.querySelector('.techRow img');return !!(i&&i.naturalWidth>0);});
await p.locator('.navItem[data-m="resume"]').click();
await p.waitForTimeout(1300);
await p.screenshot({path:'shots/y3-resume.png'});
await p.locator('.navItem[data-m="projects"]').click();
await p.waitForTimeout(1800);
await p.screenshot({path:'shots/y4-projects.png'});
const cards=await p.locator('.card').count();
await b.close();
console.log('E2E_RESULTS '+JSON.stringify({start:start,pill:pill,asciiLen:asciiLen,iconOk:iconOk,cards:cards,errors:errs}));
if(cards!==3||start!==1||pill!==1||asciiLen<3000)process.exit(1);
})().catch(e=>{console.error('E2E_FAIL',e.message);process.exit(1);});

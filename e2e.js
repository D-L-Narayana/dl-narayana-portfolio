const{chromium}=require('playwright');
(async()=>{
const b=await chromium.launch();
const p=await b.newPage({viewport:{width:1280,height:800}});
const errs=[];
p.on('pageerror',e=>errs.push('PAGE:'+e.message));
p.on('console',m=>{if(m.type()==='error')errs.push('CON:'+m.text());});
await p.goto('http://localhost:8099/',{waitUntil:'domcontentloaded'});
await p.waitForTimeout(900);
await p.screenshot({path:'shots/z0-loader.png'});
await p.waitForTimeout(3200);
await p.screenshot({path:'shots/z1-slider.png'});
const sliderVis=await p.locator('#slider').isVisible();
const t1=await p.locator('#slTitle').textContent();
await p.mouse.click(1000,400);
await p.waitForTimeout(1500);
await p.screenshot({path:'shots/z2-slide2.png'});
const n2=await p.locator('#slNum').textContent();
await p.mouse.move(640,400);
await p.mouse.wheel(0,150);
await p.waitForTimeout(2300);
await p.screenshot({path:'shots/z3-portrait.png'});
await p.locator('.navItem[data-m="projects"]').click();
await p.waitForTimeout(1800);
const cards=await p.locator('.card').count();
await p.screenshot({path:'shots/z4-projects.png'});
await p.locator('.navItem[data-m="contact"]').click();
await p.waitForTimeout(1600);
await p.screenshot({path:'shots/z5-contact.png'});
await p.locator('.navItem[data-m="home"]').click();
await p.waitForTimeout(1400);
const back=await p.locator('#slider').isVisible();
await p.screenshot({path:'shots/z6-home.png'});
await b.close();
console.log('E2E_RESULTS '+JSON.stringify({sliderVis:sliderVis,t1:t1,n2:n2,cards:cards,back:back,errors:errs}));
if(!sliderVis||cards!==3||!back)process.exit(1);
})().catch(e=>{console.error('E2E_FAIL',e.message);process.exit(1);});
